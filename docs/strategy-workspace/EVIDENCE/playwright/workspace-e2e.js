const { chromium } = require('/tmp/opencode/pwcheck/node_modules/playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('console', m => { if (m.type()==='error') errors.push('console: '+m.text()); });
  page.on('pageerror', e => errors.push('pageerror: '+e.message));
  page.on('requestfailed', r => errors.push('requestfailed: '+r.url()+' '+r.failure()?.errorText));
  const log = async (label, value) => console.log(label, value);
  await page.goto('http://127.0.0.1:16900/', {waitUntil:'networkidle'});
  await page.getByRole('button', {name:'Strategy Workspace'}).click();
  await page.waitForTimeout(400);
  await log('list h1', await page.locator('h1').innerText());
  await log('cards', await page.locator('.workspace-card').count());
  await page.getByPlaceholder('Title, ID, tag or description').fill('Liquidity');
  await page.waitForTimeout(500);
  await log('search cards', await page.locator('.workspace-card').count());
  await page.getByPlaceholder('Title, ID, tag or description').fill('');
  await page.waitForTimeout(500);
  await page.locator('.workspace-card').filter({hasText:'Liquidity Sweep'}).click();
  await page.waitForTimeout(400);
  await log('detail h1', await page.locator('h1').innerText());
  await log('variation count', await page.locator('.workspace-variation').count());
  await page.getByRole('tab', {name:/Notes/}).click();
  await page.getByPlaceholder('Record an observation, problem, decision or future experiment.').fill('E2E observation: variation link will be tested.');
  await page.getByRole('button', {name:'Add note'}).click();
  await page.waitForTimeout(500);
  await log('notes', await page.locator('.workspace-note').count());
  await page.getByRole('tab', {name:/Variations/}).click();
  await page.getByRole('button', {name:'New variation'}).click();
  await page.getByLabel('Variation title').fill('V2 — E2E Variation');
  await page.getByLabel('Description').fill('Deterministic browser workflow variation.');
  await page.getByLabel('Hypothesis').fill('A test variation should link its own run.');
  await page.getByLabel('Instruments').fill('EURUSD');
  await page.getByLabel('Timeframes').fill('M1');
  await page.getByRole('button', {name:'Save variation'}).click();
  await page.waitForTimeout(700);
  await log('variation count after create', await page.locator('.workspace-variation').count());
  const v2 = page.locator('.workspace-variation').filter({hasText:'V2 — E2E Variation'});
  await log('v2 visible', await v2.count());
  await v2.getByRole('button', {name:'Run', exact:true}).click();
  await page.waitForTimeout(700);
  await log('lab h1', await page.locator('h1').innerText());
  await log('banner', await page.locator('.workspace-lab-banner').count());
  await log('strategy', await page.getByLabel('Strategy').inputValue());
  await log('lookback', await page.getByLabel('Swing lookback').inputValue());
  await page.getByRole('button', {name:'Run backtest'}).first().click();
  await page.waitForTimeout(500);
  await page.getByText('Run result', {exact:true}).waitFor({timeout:60000});
  await page.waitForTimeout(1000);
  await log('run result', await page.locator('.panel-title').first().innerText());
  await page.screenshot({path:'/tmp/opencode/qa-workspace/run-result.png', fullPage:true});
  await page.getByRole('button', {name:'Strategy Workspace'}).click();
  await page.waitForTimeout(700);
  await log('back detail h1', await page.locator('h1').innerText());
  await page.getByRole('tab', {name:/Experiments/}).click();
  await page.waitForTimeout(300);
  await log('experiment rows', await page.locator('.workspace-variation').count(), await page.locator('table tbody tr').count());
  const body = await page.locator('body').innerText();
  await log('has V2 experiment', body.includes('V2 — E2E Variation'));
  await page.screenshot({path:'/tmp/opencode/qa-workspace/experiments.png', fullPage:true});
  fs.writeFileSync('/tmp/opencode/qa-workspace/e2e-console.json', JSON.stringify(errors,null,2));
  await log('errors', errors);
  await browser.close();
})();
